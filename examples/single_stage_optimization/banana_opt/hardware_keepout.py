CLEARANCE_ARC_WEIGHT_PROFILE_CURVATURE = "curvature"
CLEARANCE_ARC_WEIGHT_PROFILE_SMOOTH_TOROIDAL_RATE = "smooth_toroidal_rate"
CLEARANCE_ARC_WEIGHT_PROFILES = (
    CLEARANCE_ARC_WEIGHT_PROFILE_CURVATURE,
    CLEARANCE_ARC_WEIGHT_PROFILE_SMOOTH_TOROIDAL_RATE,
)


def _raised_cosine_arc_weight(signal, leg_weight, uturn_weight):
    signal = np.asarray(signal, dtype=np.float64)
    lo = float(signal.min())
    hi = float(signal.max())
    leg = float(leg_weight)
    span = hi - lo
    if span <= 1.0e-12 * max(abs(hi), 1.0):
        return np.full_like(signal, leg)
    frac = (signal - lo) / span
    smooth = 0.5 - 0.5 * np.cos(np.pi * frac)
    return leg + (float(uturn_weight) - leg) * smooth


def curvature_arc_weight(kappa, leg_weight, uturn_weight):
    """Per-station clearance weight that emphasizes high-curvature U-turn stations.

    ``kappa`` is the curve curvature at each quadrature station (1/m, one value
    per station). The lowest-curvature station (a straight inboard leg) maps to
    ``leg_weight`` and the highest (a U-turn end-cap) to ``uturn_weight`` by
    min-max normalization; intermediate stations interpolate linearly. The
    result is a NumPy constant -- it selects WHERE along the arc clearance is
    rewarded and is never itself differentiated. A (near-)constant curvature
    profile yields a uniform ``leg_weight`` array.
    """
    kappa = np.asarray(kappa, dtype=np.float64)
    lo = float(kappa.min())
    hi = float(kappa.max())
    leg = float(leg_weight)
    span = hi - lo
    # A (near-)constant curvature profile is treated as uniform: min-max
    # normalization would otherwise amplify floating-point round-off into a
    # full-range weight where there is no real U-turn to emphasize.
    if span <= 1.0e-9 * max(hi, 1.0):
        return np.full_like(kappa, leg)
    frac = (kappa - lo) / span
    return leg + (float(uturn_weight) - leg) * frac


def smooth_toroidal_rate_arc_weight(gamma, leg_weight, uturn_weight):
    """Smooth per-station clearance weight from toroidal-angle advance.

    This profile is independent of local curvature spikes. It uses the periodic
    finite-difference magnitude of the centerline toroidal angle and maps the
    resulting signal through a raised-cosine profile, so the weights are smooth
    in station index and never discontinuous. As with curvature weighting, the
    returned NumPy array is frozen at objective construction and is not
    differentiated.
    """
    gamma = np.asarray(gamma, dtype=np.float64)
    if gamma.ndim != 2 or gamma.shape[1] != 3:
        raise ValueError("gamma must have shape (n, 3)")
    phi = np.arctan2(gamma[:, 1], gamma[:, 0])
    forward = np.arctan2(
        np.sin(np.roll(phi, -1) - phi),
        np.cos(np.roll(phi, -1) - phi),
    )
    backward = np.arctan2(
        np.sin(phi - np.roll(phi, 1)),
        np.cos(phi - np.roll(phi, 1)),
    )
    toroidal_rate = 0.5 * (np.abs(forward) + np.abs(backward))
    return _raised_cosine_arc_weight(toroidal_rate, leg_weight, uturn_weight)


def resolve_clearance_arc_weight(
    leg_weight,
    uturn_weight,
    profile=CLEARANCE_ARC_WEIGHT_PROFILE_CURVATURE,
):
    """Normalize the (leg, U-turn) clearance-weight pair to an arc-weight config.

    Returns ``None`` for the uniform default (both weights 1.0), which selects
    the original unweighted-mean clearance objective byte-for-byte. Any other
    pair returns ``(profile, leg_weight, uturn_weight)`` to activate arc
    weighting. Both weights must be positive.
    """
    leg = float(leg_weight)
    uturn = float(uturn_weight)
    if leg <= 0.0 or uturn <= 0.0:
        raise ValueError("clearance leg/U-turn weights must be positive")
    profile = str(profile)
    if profile not in CLEARANCE_ARC_WEIGHT_PROFILES:
        raise ValueError(
            "clearance arc weight profile must be one of "
            f"{', '.join(CLEARANCE_ARC_WEIGHT_PROFILES)}"
        )
    if leg == 1.0 and uturn == 1.0:
        return None
    return (profile, leg, uturn)


def _station_arc_weights(curve, arc_weight):
    """Per-station clearance weights for ``curve``, or None when uniform.

    ``arc_weight`` is the resolved profile config or None. Evaluated once at
    construction from the seed geometry and then held fixed: the profile selects
    which arc stations the clearance term emphasizes and is never differentiated,
    so the term's J and dJ stay mutually consistent under optimization (the
    U-turn stations are a fixed property of the coil layout).
    """
    if arc_weight is None:
        return None
    profile, leg, uturn = arc_weight
    if profile == CLEARANCE_ARC_WEIGHT_PROFILE_CURVATURE:
        return curvature_arc_weight(curve.kappa(), leg, uturn)
    return smooth_toroidal_rate_arc_weight(curve.gamma(), leg, uturn)


def _weighted_mean_square(values, weights):
    """Mean of ``values**2`` over swept-surface samples, station-weighted.

    ``weights`` is None (plain mean -- the byte-identical default path) or a
    per-station weight vector of length ``len(values) / 26``; each station's 26
    swept-surface samples share the station weight. The weighted form is the
    arc-length-style average ``sum(w * v^2) / sum(w)``.
    """
    sq = values ** 2
    if weights is None:
        return jnp.mean(sq)
    n_samp = _SWEPT_SURFACE_QUADRATURE.shape[0]
    w_full = jnp.repeat(weights, n_samp)
    return jnp.sum(w_full * sq) / jnp.sum(w_full)


def _weighted_soft_min(values, weights, temperature_m):
    """Conservative smooth lower bound on the swept-surface sample minimum."""
    tau = jnp.asarray(temperature_m, dtype=values.dtype)
    lo = jnp.min(values)
    shifted = jnp.exp(-(values - lo) / tau)
    if weights is None:
        weighted_shifted = shifted
    else:
        n_samp = _SWEPT_SURFACE_QUADRATURE.shape[0]
        w_full = jnp.repeat(weights, n_samp)
        w_min = jnp.maximum(jnp.min(w_full), 1.0e-300)
        weighted_shifted = (w_full / w_min) * shifted
    return lo - tau * jnp.log(jnp.maximum(jnp.sum(weighted_shifted), 1.0e-300))


def _normalize_clearance_target_margin(target_margin, curves):
    """Return scalar or swept-sample target margins validated against curves."""
    target = np.asarray(target_margin, dtype=np.float64)
    if target.ndim == 0:
        value = float(target)
        if not np.isfinite(value) or value <= 0.0:
            raise ValueError(
                f"target_margin {value} m must be finite and positive")
        return value
    if target.ndim != 1:
        raise ValueError("target_margin must be a scalar or 1-D margin vector")
    if target.size == 0:
        raise ValueError("target_margin vector must be non-empty")
    if not np.isfinite(target).all() or np.any(target <= 0.0):
        raise ValueError("target_margin vector entries must be finite and positive")
    n_quadpoints = {np.asarray(curve.gamma()).shape[0] for curve in curves}
    if len(n_quadpoints) != 1:
        raise ValueError(
            "vector target_margin requires all curves to have the same "
            "quadpoint count")
    n_quad = next(iter(n_quadpoints))
    n_samp = _SWEPT_SURFACE_QUADRATURE.shape[0]
    if target.size == n_quad:
        return np.repeat(target, n_samp)
    if target.size == n_quad * n_samp:
        return target.copy()
    raise ValueError(
        "target_margin vector length must equal the curve quadpoint count "
        f"({n_quad}) or swept-surface sample count ({n_quad * n_samp}); "
        f"got {target.size}")


def hardware_sdf_keepout_pure(gammac, grid_fields, effective_margin_m, half_w,
                              half_d, winding_r0, weights=None):
    """SDF-backed keepout on sampled swept Type KK surface points."""
    surface_points = swept_channel_surface_points(
        gammac, half_w, half_d, winding_r0
    )
    scale = jnp.maximum(effective_margin_m, 1.0e-6)
    phi = _sdf_gridset_trilinear(
        grid_fields,
        surface_points,
        outside_value=effective_margin_m,
    )
    violation = jnp.maximum(effective_margin_m - phi, 0.0) / scale
    return _weighted_mean_square(violation, weights)


def hardware_sdf_free_space_reward_pure(gammac, grid_fields, effective_margin_m,
                                        half_w, half_d, winding_r0,
                                        weights=None):
    """Bounded reward for sampled swept Type KK surface clearance in CAD SDF."""
    surface_points = swept_channel_surface_points(
        gammac, half_w, half_d, winding_r0
    )
    scale = jnp.maximum(effective_margin_m, 1.0e-6)
    phi = _sdf_gridset_trilinear(
        grid_fields,
        surface_points,
        outside_value=effective_margin_m,
    )
    clearance_fraction = jnp.clip(phi, 0.0, effective_margin_m) / scale
    return -_weighted_mean_square(clearance_fraction, weights)


def hardware_sdf_clearance_hinge_pure(gammac, grid_fields, effective_margin_m,
                                      target_margin_m, half_w, half_d,
                                      winding_r0, weights=None):
    """One-sided hinge driving sampled swept Type KK SDF clearance up to target.

    The hinge penalizes only the shortfall ``target_margin_m - phi`` below the
    positive target clearance (zero once a sample clears it), so the optimizer
    steers the worst sampled clearance toward ``target_margin_m`` -- the same
    metre-frame metric the posthoc swept-solid CAD oracle scores. Unlike the
    NumPy hard-min diagnostics, this is built on the differentiable ``phi``
    array and is gradient-live. Steering proxy only; ``audit_hardware_contacts``
    stays the promotion gate.
    """
    surface_points = swept_channel_surface_points(
        gammac, half_w, half_d, winding_r0
    )
    phi = _sdf_gridset_trilinear(
        grid_fields,
        surface_points,
        outside_value=effective_margin_m,
    )
    violation = jnp.maximum(jnp.asarray(target_margin_m) - phi, 0.0)
    return _weighted_mean_square(violation, weights)


def hardware_sdf_clearance_softmin_hinge_pure(
    gammac,
    grid_fields,
    effective_margin_m,
    target_margin_m,
    soft_min_temperature_m,
    half_w,
    half_d,
    winding_r0,
    weights=None,
):
    """One-sided hinge on a smooth approximation to the worst SDF clearance."""
    surface_points = swept_channel_surface_points(
        gammac, half_w, half_d, winding_r0
    )
    phi = _sdf_gridset_trilinear(
        grid_fields,
        surface_points,
        outside_value=effective_margin_m,
    )
    clearance_excess = phi - jnp.asarray(target_margin_m)
    soft_min_excess = _weighted_soft_min(
        clearance_excess, weights, soft_min_temperature_m
    )
    violation = jnp.maximum(-soft_min_excess, 0.0)
    return violation ** 2


class CurveHardwareKeepout(Optimizable):
    r"""
    Penalty steering the banana coils away from fixed in-vessel hardware
    sampled in ``hardware_keepout.json`` (shells, sensors, solenoid, REMC,
    limiter, and quartz-spool rings) — the keep-out analogue of
    :class:`simsopt.geo.curveobjectives.CurveSurfaceDistance` with the surface
    quadrature replaced by a static sampled point cloud.

    Parameters
    ----------
    curves : list of simsopt.geo.curve.Curve
        Full symmetry-expanded banana coil set (each copy meets different
        hardware). Each must expose ``gamma()``, ``gammadash()``,
        ``dgamma_by_dcoeff_vjp`` and ``dgammadash_by_dcoeff_vjp``.
    points : (P, 3) array
        Hardware surface sample points in the machine metre frame
        (see :func:`load_hardware_keepout`).
    minimum_distance : float
        Centerline keep-out threshold, m
        (``HARDWARE_KEEPOUT_MIN_DISTANCE_M``).
    point_weight : float
        Surface patch area per point (sampling spacing^2), m^2.
    chunk_size : int, optional
        Cloud chunk size for candidate pruning / single-shape JIT.
    """

    def __init__(self, curves, points, minimum_distance, point_weight,
                 half_w=TYPE_KK_OUTER_CHANNEL_HALF_WIDTH_BINORMAL_M,
                 half_d=TYPE_KK_OUTER_CHANNEL_HALF_DEPTH_NORMAL_M,
                 winding_r0=BANANA_WINDING_SURFACE_MAJOR_RADIUS_M,
                 chunk_size=8192):
        self.curves = curves
        self.minimum_distance = float(minimum_distance)
        self.point_weight = float(point_weight)
        self.half_w = float(half_w)
        self.half_d = float(half_d)
        # Fallback winding radius for non-CWS lineages (no embedded surface).
        # ``winding_r0`` stays the public attribute/kwarg for back-compat; the
        # live value is read from the curves' CWS surf each evaluation (B1.3).
        self._winding_r0_fallback = float(winding_r0)
        # The contract distance is centerline corner-reach + safety; the box now
        # carries the corner reach, so the hinge margin is the safety remainder.
        corner_reach = float(np.hypot(half_w, half_d))
        self.margin = self.minimum_distance - corner_reach
        if self.margin <= 0.0:
            raise ValueError(
                f"minimum_distance {minimum_distance} m must exceed the bracket "
                f"corner reach {corner_reach:.4f} m to leave a positive margin")

        pts = np.ascontiguousarray(np.asarray(points, dtype=np.float64))
        if pts.ndim != 2 or pts.shape[1] != 3 or pts.shape[0] == 0:
            raise ValueError(
                f"points must be a non-empty (P, 3) array, got {pts.shape}")
        # Toroidal sort -> spatially coherent chunks -> effective pruning.
        order = np.argsort(np.arctan2(pts[:, 1], pts[:, 0]))
        pts = pts[order]
        pad = (-len(pts)) % chunk_size
        if pad:
            pts = np.vstack([pts, np.full((pad, 3), _PAD_COORDINATE)])
        self._chunks_np = [
            pts[i:i + chunk_size] for i in range(0, len(pts), chunk_size)
        ]
        self._chunks = [jnp.asarray(c) for c in self._chunks_np]
        # Static per-chunk AABBs over the REAL points only (pads excluded so
        # they never widen a chunk's box).
        self._chunk_bounds = []
        for chunk in self._chunks_np:
            real = chunk[np.any(chunk != _PAD_COORDINATE, axis=1)]
            self._chunk_bounds.append((real.min(axis=0), real.max(axis=0)))

        # winding_r0 enters as a CALL-TIME argument (sourced live in J/dJ) so the
        # frame tracks the moving winding surface; it stays in the JAX-traced path
        # (smooth cos/sin/normalize), preserving differentiability. B1.3:
        # value-live; frame-orientation gradient deferred (the curve VJP
        # dgamma_by_dsurf still carries the centerline-translation gradient).
        self.J_jax = jit(lambda gammac, pts_, winding_r0_: hardware_keepout_pure(
            gammac, pts_, self.point_weight, self.half_w, self.half_d,
            self.margin, winding_r0_))
        self.dJ_dgamma = jit(
            lambda gammac, pts_, winding_r0_: grad(self.J_jax, argnums=0)(
                gammac, pts_, winding_r0_))
        # B1.3 frame-orientation partial: dJ/d winding_r0 at FIXED centerline.
        # winding_r0 enters the U-channel frame (radial/tangential) explicitly,
        # so this is the R0 gradient the centerline curve VJP cannot carry. It is
        # zero for a midplane cloud and nonzero where the frame rolls with R0
        # (off-midplane); measured ~40% of dJ/dR0 on the frame-split fixture.
        self.dJ_dwinding_r0 = jit(
            lambda gammac, pts_, winding_r0_: grad(self.J_jax, argnums=2)(
                gammac, pts_, winding_r0_))
        self.candidates = None
        super().__init__(depends_on=curves)

    @property
    def winding_r0(self):
        """Fallback winding major radius (constructor value), m.

        Public back-compat attribute. The value the term *scores* against is the
        live :meth:`live_winding_r0`, which equals this for a frozen winding
        surface and for non-CWS lineages.
        """
        return self._winding_r0_fallback

    def live_winding_r0(self):
        """Live winding major radius the frame is currently measured about, m."""
        return live_winding_r0(self.curves, self._winding_r0_fallback)

    def recompute_bell(self, parent=None):
        self.candidates = None

    def compute_candidates(self):
        """(curve, chunk) pairs whose inflated AABBs overlap — a conservative
        superset of pairs with any quadpoint within ``minimum_distance`` of a
        cloud point, so the pruning is exact for the hinge."""
        if self.candidates is None:
            d = self.minimum_distance
            candidates = []
            for i, curve in enumerate(self.curves):
                g = curve.gamma()
                glo, ghi = g.min(axis=0) - d, g.max(axis=0) + d
                for j, (clo, chi) in enumerate(self._chunk_bounds):
                    if np.all(glo <= chi) and np.all(clo <= ghi):
                        candidates.append((i, j))
            self.candidates = candidates

    def shortest_distance(self):
        """Minimum hardware-point-to-U-channel-envelope distance over all
        curves, m (NumPy diagnostic). Negative is impossible here (clamped at
        the box surface); 0 means the metal touches the cloud. Pads sit ~1 km
        away and cannot win the minimum."""
        best = np.inf
        winding_r0 = self.live_winding_r0()
        for curve in self.curves:
            g = np.asarray(curve.gamma(), dtype=np.float64)
            t, gw, gd, hseg = (np.asarray(x) for x in _bracket_frame(
                jnp.asarray(g), winding_r0))
            for chunk in self._chunks_np:
                d = chunk[None, :, :] - g[:, None, :]
                a = np.abs(np.sum(d * t[:, None, :], axis=2))
                b = np.abs(np.sum(d * gw[:, None, :], axis=2))
                c = np.abs(np.sum(d * gd[:, None, :], axis=2))
                da = np.maximum(a - hseg[:, None], 0.0)
                db = np.maximum(b - self.half_w, 0.0)
                dc = np.maximum(c - self.half_d, 0.0)
                box = np.sqrt(da ** 2 + db ** 2 + dc ** 2)
                best = min(best, float(box.min()))
        return best

    # ── Optimizable API ────────────────────────────────────────────────
    def J(self):
        self.compute_candidates()
        winding_r0 = self.live_winding_r0()
        res = 0.0
        for i, j in self.candidates:
            gammac = self.curves[i].gamma()
            res += float(self.J_jax(gammac, self._chunks[j], winding_r0))
        return res

    @derivative_dec
    def dJ(self):
        self.compute_candidates()
        winding_r0 = self.live_winding_r0()
        # The swept-bracket frame depends on winding_r0 = the master surf's
        # rc(0,0) EXPLICITLY (separate from the centerline path), so dJ/d rc(0,0)
        # gains a frame-orientation partial the curve VJP cannot carry. Inject it
        # ONLY when rc(0,0) is a free DOF -> non-CWS lineages and non-free-R0 runs
        # stay byte-identical (and skip the partial's grad evals).
        master_surf = _master_cws_surf(self.curves)
        free_winding_r0 = master_surf is not None and not master_surf.is_fixed(
            "rc(0,0)"
        )
        dgamma_vecs = [np.zeros_like(c.gamma()) for c in self.curves]
        frame_partial = 0.0
        for i, j in self.candidates:
            gammac = self.curves[i].gamma()
            chunk = self._chunks[j]
            dgamma_vecs[i] += np.asarray(self.dJ_dgamma(gammac, chunk, winding_r0))
            if free_winding_r0:
                frame_partial += float(
                    self.dJ_dwinding_r0(gammac, chunk, winding_r0)
                )
        res = [
            self.curves[i].dgamma_by_dcoeff_vjp(dgamma_vecs[i])
            for i in range(len(self.curves))
        ]
        total = sum(res)
        if free_winding_r0:
            total = total + _winding_r0_frame_derivative(master_surf, frame_partial)
        return total

    return_fn_map = {'J': J, 'dJ': dJ}


class CurveHardwareSdfKeepout(Optimizable):
    r"""
    Optimizer-visible CAD distance-field proxy for static hardware keepout.

    The objective samples the viewer-matched Type KK swept U-channel surface and
    queries one or more manifest-bound hardware distance grids.  It is a
    steering proxy only: ``hardware_contact_report`` remains the direct CAD
    oracle for promotion and handoff.

    winding_r0 (the master CWS ``rc(0,0)``) enters the swept-bracket frame, so
    under ``--winding-surface-free-r0`` dJ/d rc(0,0) carries a frame-orientation
    partial in addition to the centerline VJP. This term and its siblings
    (:class:`CurveHardwareSdfFreeSpaceReward`, :class:`CurveHardwareSdfClearanceHinge`)
    inject that partial via ``grad(self.J_jax, argnums=3)`` +
    :func:`_winding_r0_frame_derivative`, guarded on a free ``rc(0,0)`` so
    non-free-R0 runs stay byte-identical (mirrors the point-cloud keepout and the
    vessel-envelope terms). This matters because under ``--hardware-keepout-backend
    sdf`` the SDF keepout *is* the primary keepout (taking the role the point-cloud
    term holds by default), and the live ``--winding-surface-free-r0`` space-squeeze
    campaign runs SDF + free-R0 together -- so the SDF frame partial, not the
    point-cloud one, governs rc(0,0) steering there. As always the term is a
    steering proxy only: ``hardware_contact_report`` is the CAD oracle for promotion.
    """

    def __init__(self, curves, sdf_data,
                 half_w=TYPE_KK_OUTER_CHANNEL_HALF_WIDTH_BINORMAL_M,
                 half_d=TYPE_KK_OUTER_CHANNEL_HALF_DEPTH_NORMAL_M,
                 winding_r0=BANANA_WINDING_SURFACE_MAJOR_RADIUS_M,
                 clearance_leg_weight=1.0,
                 clearance_uturn_weight=1.0,
                 clearance_arc_weight_profile=CLEARANCE_ARC_WEIGHT_PROFILE_CURVATURE):
        if not isinstance(sdf_data, HardwareSdfData):
            raise TypeError("sdf_data must come from load_hardware_sdf(...)")
        if not sdf_data.groups:
            raise ValueError("hardware SDF payload must contain at least one group")
        self.curves = curves
        self.sdf_data = sdf_data
        self.half_w = float(half_w)
        self.half_d = float(half_d)
        # Arc weighting (None = uniform, byte-identical default).
        # Frozen here from the seed geometry so J and dJ stay mutually
        # consistent (the weight profile is data, not an optimized quantity).
        self._arc_weight = resolve_clearance_arc_weight(
            clearance_leg_weight,
            clearance_uturn_weight,
            clearance_arc_weight_profile,
        )
        self._station_weights = [
            _station_arc_weights(c, self._arc_weight) for c in curves
        ]
        # Fallback winding radius for non-CWS lineages; the live value (read from
        # the curves' CWS surf each evaluation) is what the frame scores against.
        self._winding_r0_fallback = float(winding_r0)
        self._groups = [
            {
                "label": group.label,
                "grid_fields": _sdf_group_jax_fields(group),
                "grid_fields_np": _sdf_group_numpy_fields(group),
                "effective_margin": float(group.effective_margin_m),
            }
            for group in sdf_data.groups
        ]
        # winding_r0 is a CALL-TIME argument sourced live in J/dJ (B1.3:
        # value-live; frame-orientation gradient deferred -- the curve VJP keeps
        # the centerline-translation gradient). It stays in the JAX-traced path.
        self.J_jax = jit(
            lambda gammac, grid_fields, effective_margin, winding_r0_, weights:
            hardware_sdf_keepout_pure(
                gammac,
                grid_fields,
                effective_margin,
                self.half_w,
                self.half_d,
                winding_r0_,
                weights,
            )
        )
        self.dJ_dgamma = jit(
            lambda gammac, grid_fields, effective_margin, winding_r0_, weights:
            grad(self.J_jax, argnums=0)(
                gammac, grid_fields, effective_margin, winding_r0_, weights
            )
        )
        # B1.3 frame-orientation partial: winding_r0 (the master CWS rc(0,0))
        # enters the swept-bracket frame at argnums=3, separate from the centerline
        # VJP. Injected in dJ only when rc(0,0) is free -> non-free-R0 runs stay
        # byte-identical (mirrors the point-cloud keepout / vessel-envelope terms).
        self.dJ_dwinding_r0 = jit(
            lambda gammac, grid_fields, effective_margin, winding_r0_, weights:
            grad(self.J_jax, argnums=3)(
                gammac, grid_fields, effective_margin, winding_r0_, weights
            )
        )
        super().__init__(depends_on=curves)

    @property
    def winding_r0(self):
        """Fallback winding major radius (constructor value), m. See
        :meth:`live_winding_r0` for the value the term scores against."""
        return self._winding_r0_fallback

    def live_winding_r0(self):
        """Live winding major radius the frame is currently measured about, m."""
        return live_winding_r0(self.curves, self._winding_r0_fallback)

    @property
    def group_labels(self):
        return self.sdf_data.group_labels

    def _group_value(self, gammac, group, winding_r0, weights):
        return float(
            self.J_jax(
                gammac,
                group["grid_fields"],
                group["effective_margin"],
                winding_r0,
                weights,
            )
        )

    def J(self):
        winding_r0 = self.live_winding_r0()
        total = 0.0
        for curve_index, curve in enumerate(self.curves):
            gammac = curve.gamma()
            weights = self._station_weights[curve_index]
            for group in self._groups:
                total += self._group_value(gammac, group, winding_r0, weights)
        return total

    @derivative_dec
    def dJ(self):
        winding_r0 = self.live_winding_r0()
        # winding_r0 (the master CWS rc(0,0)) enters the swept-bracket frame
        # EXPLICITLY, so dJ/d rc(0,0) gains a frame-orientation partial the curve
        # VJP cannot carry. Accumulate it in the SAME pass as the centerline VJP
        # and inject ONLY when rc(0,0) is a free DOF -> non-CWS lineages and
        # non-free-R0 runs stay byte-identical (and skip the partial's grad evals).
        master_surf = _master_cws_surf(self.curves)
        free_winding_r0 = master_surf is not None and not master_surf.is_fixed(
            "rc(0,0)"
        )
        dgamma_vecs = [np.zeros_like(c.gamma()) for c in self.curves]
        frame_partial = 0.0
        for curve_index, curve in enumerate(self.curves):
            gammac = curve.gamma()
            weights = self._station_weights[curve_index]
            for group in self._groups:
                dgamma_vecs[curve_index] += np.asarray(
                    self.dJ_dgamma(
                        gammac,
                        group["grid_fields"],
                        group["effective_margin"],
                        winding_r0,
                        weights,
                    )
                )
                if free_winding_r0:
                    frame_partial += float(
                        self.dJ_dwinding_r0(
                            gammac,
                            group["grid_fields"],
                            group["effective_margin"],
                            winding_r0,
                            weights,
                        )
                    )
        total = sum(
            self.curves[i].dgamma_by_dcoeff_vjp(dgamma_vecs[i])
            for i in range(len(self.curves))
        )
        if free_winding_r0:
            total = total + _winding_r0_frame_derivative(
                master_surf, frame_partial
            )
        return total

    def per_group_min_clearance(self):
        """Minimum sampled swept-surface SDF value per represented group, m."""
        best = {group["label"]: np.inf for group in self._groups}
        winding_r0 = self.live_winding_r0()
        for curve in self.curves:
            surface_points = np.asarray(
                swept_channel_surface_points(
                    jnp.asarray(curve.gamma()),
                    self.half_w,
                    self.half_d,
                    winding_r0,
                ),
                dtype=np.float64,
            )
            for group in self._groups:
                values = _sdf_gridset_trilinear_numpy(
                    group["grid_fields_np"],
                    surface_points,
                    outside_value=group["effective_margin"],
                )
                best[group["label"]] = min(
                    best[group["label"]], float(values.min())
                )
        return best

    def shortest_distance(self):
        """Minimum sampled swept-surface SDF value, m.

        Negative values indicate the sampled swept surface is inside a signed
        field.  Outside-grid samples use the manifest-guaranteed safe margin.
        The name is retained for the existing results-writer contract;
        ``shortest_clearance`` is an alias for callers that want signed wording.
        """
        return min(self.per_group_min_clearance().values())

    def shortest_clearance(self):
        return self.shortest_distance()

    return_fn_map = {'J': J, 'dJ': dJ}


